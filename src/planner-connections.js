// Sistema para criar conexões automaticamente durante execução de roteiros
import { getConnections, setConnections, getNextHubId, resources } from './state.js';
import { redraw } from './drawing.js';
import { getCurrentConnectionColor } from './color-palette.js';
import { getHubById, registerConnectionHub } from './hubs.js';
import { updateConnectionDistancesTable } from './flow-metrics.js';
import { getCachedPath, isCacheValid } from './planner-path-cache.js';

/**
 * Cria ou reutiliza uma conexão entre dois hubs (incluindo hubs virtuais)
 * @param {string} startHubId - ID do hub de origem (pode ser hub virtual)
 * @param {string} endHubId - ID do hub de destino
 * @param {number} width - Largura da conexão (padrão 60cm)
 * @param {Object} virtualHubPositions - Posições de hubs virtuais {hubId: {x, y}}
 * @param {string|null} overrideColor - Cor específica para a conexão (da camada do planner)
 * @returns {Object} Conexão criada ou existente
 */
export function ensureConnectionBetweenHubs(startHubId, endHubId, width = 60, virtualHubPositions = new Map(), overrideColor = null) {
    const connections = getConnections();
    
    // Verificar se já existe uma conexão entre esses hubs (em qualquer direção)
    const existing = connections.find(conn => 
        (conn.startHubId === startHubId && conn.endHubId === endHubId) ||
        (conn.startHubId === endHubId && conn.endHubId === startHubId)
    );
    
    if (existing) {
        // Verificar se a direção está correta
        const isReversed = existing.startHubId === endHubId && existing.endHubId === startHubId;
        if (existing.isAutoGenerated && !existing.disableAutoAnimation) {
            existing.disableAutoAnimation = true;
        }
        
        // Incrementar contador de uso para métricas cumulativas
        existing.usageCount = (existing.usageCount || 0) + 1;
        
        // Atualizar tabela de distâncias para refletir o novo uso
        updateConnectionDistancesTable();

        if (isReversed && existing.path && existing.path.length > 0) {
            return {
                ...existing,
                id: `${existing.id}_reversed`,
                startHubId: startHubId,
                endHubId: endHubId,
                path: [...existing.path].reverse(),
                disableAutoAnimation: true
            };
        } else {
            return existing;
        }
    }
    
    // Obter informações dos hubs (reais ou virtuais)
    const startHub = startHubId.startsWith('virtual_hub_') 
        ? { x: virtualHubPositions.get(startHubId)?.x, y: virtualHubPositions.get(startHubId)?.y, resourceId: null }
        : getHubById(startHubId);
        
    const endHub = getHubById(endHubId);
    
    if (!startHub || !endHub) {
        console.error(`[PlannerConnections] ✗ Hubs não encontrados: startHub=${!!startHub}, endHub=${!!endHub}`);
        if (startHubId.startsWith('virtual_hub_')) {
            console.error(`[PlannerConnections] Hub virtual ${startHubId} sem posição registrada`);
        }
        return null;
    }
    
    // Criar nova conexão
    const newConnection = {
        id: `planner_connection_${Date.now()}`,
        startHubId: startHubId,
        endHubId: endHubId,
        color: overrideColor || getCurrentConnectionColor(),
        name: `Conexão Automática`,
        width: width,
        path: [],
        isAutoGenerated: true, // Marca que foi gerada pelo roteiro
        disableAutoAnimation: true,
        usageCount: 1 // Inicializar contador de uso
    };

    // REGISTRAR A CONEXÃO NOS HUBS
    // Isso é crucial para que o movimento do recurso atualize a conexão
    if (!startHubId.startsWith('virtual_hub_') && startHub) {
        if (!startHub.connectionIds) startHub.connectionIds = [];
        if (!startHub.connectionIds.includes(newConnection.id)) {
            startHub.connectionIds.push(newConnection.id);
            // Se o hub tem resourceId, precisamos atualizar o registro global/recurso
            if (startHub.resourceId) {
                // Encontrar o recurso para passar para registerConnectionHub
                // Como não temos acesso direto a resources aqui, vamos confiar que registerConnectionHub lida com isso
                // ou atualizar o objeto hub diretamente se ele for uma referência viva
                // O ideal é chamar registerConnectionHub se possível
                // Mas registerConnectionHub precisa do objeto resource.
                // Vamos tentar atualizar apenas o objeto hub retornado por getHubById, 
                // pois getHubById retorna o objeto do registro global.
            }
        }
    }

    if (endHub) {
        if (!endHub.connectionIds) endHub.connectionIds = [];
        if (!endHub.connectionIds.includes(newConnection.id)) {
            endHub.connectionIds.push(newConnection.id);
        }
    }
    
    // Calcular path
    const startWorld = { x: startHub.x, y: startHub.y };
    const endWorld = { x: endHub.x, y: endHub.y };
    
    // Tentar usar pathfinding se disponível
    const isStartVirtual = startHubId.startsWith('virtual_hub_');
    const isEndVirtual = endHubId.startsWith('virtual_hub_'); // Futuro suporte
    // Boundary opening hubs: sem resourceId mas com posição absoluta (docas, expedição, recebimento)
    const isStartBoundary = !isStartVirtual && !startHub.resourceId && typeof startHub.x === 'number' && typeof startHub.y === 'number';
    const isEndBoundary = !isEndVirtual && !endHub.resourceId && typeof endHub.x === 'number' && typeof endHub.y === 'number';

    // ========== CONSULTAR CACHE PRIMEIRO ==========
    // Tentar usar cache pré-calculado se disponível (apenas para hubs não-virtuais)
    if (!isStartVirtual && !isEndVirtual) {
        const cacheValid = isCacheValid();
        
        if (cacheValid) {
            // Tentar ambas as direções do cache
            let cachedPath = getCachedPath(`hub:${startHubId}`, `hub:${endHubId}`, width);
            let isReversed = false;
            
            if (!cachedPath || cachedPath.length === 0) {
                // Tentar direção inversa
                cachedPath = getCachedPath(`hub:${endHubId}`, `hub:${startHubId}`, width);
                if (cachedPath && cachedPath.length > 0) {
                    cachedPath = [...cachedPath].reverse();
                    isReversed = true;
                }
            }
            
            if (cachedPath && cachedPath.length > 0) {
                newConnection.path = cachedPath;
                newConnection.isFallback = false;
                
                // Adicionar à lista de conexões
                connections.push(newConnection);
                setConnections(connections);
                
                redraw();
                updateConnectionDistancesTable();
                
                return newConnection;
            } else {
            }
        }
    }
    // ========== FIM CONSULTA CACHE ==========

    if (typeof window !== 'undefined' && window.findPathWithAnchors && 
        (isStartVirtual || isStartBoundary || (startHub.resourceId && typeof startHub.localX === 'number' && typeof startHub.localY === 'number')) &&
        (isEndVirtual || isEndBoundary || (endHub.resourceId && typeof endHub.localX === 'number' && typeof endHub.localY === 'number'))) {
        try {
            
            let endResourceId = endHub.resourceId;
            let endAnchor = { x: endHub.localX, y: endHub.localY };

            // Verificar se o recurso de destino existe no andar atual (apenas se não for virtual)
            if (!isEndVirtual) {
                const endResourceExists = resources.some(r => r.id === endResourceId);
                if (!endResourceExists) {
                    // Fallback: Procurar uma escada no andar atual para servir de destino
                    const stair = resources.find(r => r.type === 'stair' || r.stairConfig);
                    if (stair) {
                        endResourceId = stair.id;
                        
                        // Marcar conexão como redirecionada para escada
                        newConnection.stairRedirect = {
                            stairId: stair.id,
                            originalTargetHubId: endHubId,
                            originalTargetResourceId: endHub.resourceId
                        };
                        console.log(`[ConnLog] stairRedirect criado:`, JSON.stringify(newConnection.stairRedirect));
                        
                        // Tentar usar o ponto de entrada da escada
                        if (stair.stairConfig?.orientation?.entryPoint) {
                            const entry = stair.stairConfig.orientation.entryPoint;
                            // Calcular âncora local relativa ao CENTROIDE da escada
                            // (porque calculateWorldAnchorPosition usa centroid como origem)
                            let cx = 0, cy = 0;
                            if (stair.vertices && stair.vertices.length > 0) {
                                for (const v of stair.vertices) { cx += v[0]; cy += v[1]; }
                                cx /= stair.vertices.length;
                                cy /= stair.vertices.length;
                            } else {
                                // Fallback: usar x,y como centro aproximado
                                cx = stair.x || 0;
                                cy = stair.y || 0;
                            }
                            
                            endAnchor = {
                                x: entry.x - cx,
                                y: entry.y - cy
                            };
                        } else {
                            // Fallback para o centro (0,0 relativo se não tivermos info melhor)
                            endAnchor = { x: 0, y: 0 };
                        }
                    }
                }
            }

            let startAnchorObj;
            if (isStartVirtual || isStartBoundary) {
                startAnchorObj = {
                    isVirtual: true,
                    position: { x: startHub.x, y: startHub.y }
                };
            } else {
                startAnchorObj = {
                    resourceId: startHub.resourceId,
                    anchor: { x: startHub.localX, y: startHub.localY }
                };
            }
            
            let endAnchorObj;
            if (isEndBoundary) {
                endAnchorObj = {
                    isVirtual: true,
                    position: { x: endHub.x, y: endHub.y }
                };
            } else {
                endAnchorObj = {
                    resourceId: endResourceId,
                    anchor: endAnchor
                };
            }
            
            const calculatedPath = window.findPathWithAnchors(
                startAnchorObj, 
                endAnchorObj, 
                null, 
                width
            );
            
            if (calculatedPath && calculatedPath.length > 0) {
                newConnection.path = calculatedPath;
                newConnection.isFallback = !!calculatedPath.isFallback;
            } else {
                newConnection.path = [startWorld, endWorld];
                newConnection.isFallback = true;
            }
        } catch (error) {
            newConnection.path = [startWorld, endWorld];
            newConnection.isFallback = true;
        }
    } else {
        // Pathfinding não disponível — linha reta
        newConnection.path = [startWorld, endWorld];
        newConnection.isFallback = true;
    }
    
    // Adicionar à lista de conexões
    connections.push(newConnection);
    setConnections(connections);
    
    // Redesenhar canvas
    redraw();
    
    // Atualizar tabela de distâncias
    updateConnectionDistancesTable();
    
    return newConnection;
}

/**
 * Remove todas as conexões auto-geradas pelo planner
 */
export function clearAutoGeneratedConnections() {
    const connections = getConnections();
    const filtered = connections.filter(conn => !conn.isAutoGenerated);
    
    const removedCount = connections.length - filtered.length;
    if (removedCount > 0) {
        setConnections(filtered);
        redraw();
        updateConnectionDistancesTable();
    }
}

/**
 * Obtém o caminho de uma conexão entre dois hubs
 * @param {string} startHubId 
 * @param {string} endHubId 
 * @returns {Array} Array de pontos {x, y} do caminho
 */
export function getConnectionPath(startHubId, endHubId) {
    const connection = ensureConnectionBetweenHubs(startHubId, endHubId);
    return connection ? connection.path : [];
}
