// Função auxiliar para encontrar hub em uma posição
function findHubAtPosition(position) {
    if (!position) return null;
    
    const tolerance = 10; // pixels
    const allHubs = getAllHubRecords();
    
    for (const hub of allHubs) {
        const dx = Math.abs(hub.x - position.x);
        const dy = Math.abs(hub.y - position.y);
        if (dx <= tolerance && dy <= tolerance) {
            return hub.id;
        }
    }
    
    return null;
}

