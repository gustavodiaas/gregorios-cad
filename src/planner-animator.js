// Atualizar posição do token sendo carregado
function updateCarryingTokenPosition(token, worldPos) {
    if (!token || !worldPos) return;
    
    const scale = getScale();
    const offsetX = getOffsetXCanvas();
    const offsetY = getOffsetYCanvas();
    
    const screenX = worldPos.x * scale + offsetX;
    const screenY = worldPos.y * scale + offsetY;
    
    // Posicionar acima e à direita do sprite
    token.style.left = `${screenX + 15}px`;
    token.style.top = `${screenY - 40}px`;
}

