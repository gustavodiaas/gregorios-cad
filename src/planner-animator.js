// Flag para indicar que o estoque mudou e o canvas precisa ser redesenhado
let _stockDirty = false;

// Atualizar propriedade _liveStock no recurso-pai do hub
function syncResourceLiveStock(hubId) {
    const hub = getHubById(hubId);
    if (!hub || !hub.resourceId) return;
    const resource = resources.find(r => r.id === hub.resourceId);
    if (!resource) return;
    // Somar estoque de todos os hubs do recurso
    const resourceHubs = getHubsForResource(hub.resourceId);
    let total = 0;
    resourceHubs.forEach(h => { total += (hubFinishedStock.get(h.id) || 0); });
    resource._liveStock = total;
    _stockDirty = true;
}

// Adicionar acabado a um hub
function addFinishedToHub(hubId, count = 1) {
    const currentStock = hubFinishedStock.get(hubId) || 0;
    hubFinishedStock.set(hubId, currentStock + count);
    syncResourceLiveStock(hubId);
}

// Remover acabado de um hub (retorna true se havia estoque suficiente)
function removeFinishedFromHub(hubId, count = 1) {
    const currentStock = hubFinishedStock.get(hubId) || 0;
    if (currentStock >= count) {
        hubFinishedStock.set(hubId, currentStock - count);
        syncResourceLiveStock(hubId);
        return true;
    }
    return false;
}

// Verificar se hub tem acabados disponíveis (com quantidade mínima)
function hasFinishedInHub(hubId, minQty = 1) {
    return (hubFinishedStock.get(hubId) || 0) >= minQty;
}

// Obter quantidade de acabados em um hub
function getFinishedCount(hubId) {
    return hubFinishedStock.get(hubId) || 0;
}

