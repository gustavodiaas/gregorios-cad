// Obter estoque total do recurso-pai de um hub (soma de todos os hubs do recurso)
function getResourceStockForHub(hubId) {
    const hub = getHubById(hubId);
    if (!hub || !hub.resourceId) return hubFinishedStock.get(hubId) || 0;
    const resourceHubs = getHubsForResource(hub.resourceId);
    let total = 0;
    resourceHubs.forEach(h => { total += (hubFinishedStock.get(h.id) || 0); });
    return total;
}

// Verificar se o recurso-pai do hub tem acabados suficientes (espalhados por seus hubs)
function hasFinishedInResource(hubId, minQty = 1) {
    return getResourceStockForHub(hubId) >= minQty;
}

// Remover acabados no nível do recurso: primeiro tenta do hub indicado,
// depois percorre os demais hubs do mesmo recurso até completar a quantidade.
// Retorna true se conseguiu remover tudo, false se não havia estoque suficiente.
function removeFinishedFromResource(hubId, count = 1) {
    // Verificar se o recurso como um todo tem estoque suficiente
    if (!hasFinishedInResource(hubId, count)) return false;

    const hub = getHubById(hubId);
    const resourceHubs = (hub && hub.resourceId) ? getHubsForResource(hub.resourceId) : [];

    let remaining = count;

    // Primeiro, consumir do hub alvo
    const localStock = hubFinishedStock.get(hubId) || 0;
    if (localStock > 0) {
        const take = Math.min(localStock, remaining);
        hubFinishedStock.set(hubId, localStock - take);
        remaining -= take;
    }

    // Se ainda falta, consumir dos demais hubs do mesmo recurso
    if (remaining > 0 && resourceHubs.length > 0) {
        for (const h of resourceHubs) {
            if (h.id === hubId) continue; // já consumido acima
            const stock = hubFinishedStock.get(h.id) || 0;
            if (stock > 0) {
                const take = Math.min(stock, remaining);
                hubFinishedStock.set(h.id, stock - take);
                remaining -= take;
                if (remaining <= 0) break;
            }
        }
    }

    // Sincronizar _liveStock no recurso-pai
    syncResourceLiveStock(hubId);
    return remaining <= 0;
}

