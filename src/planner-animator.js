function updateLoadingProgress(current, total) {
    loadingOverlay = document.getElementById('plannerLoadingOverlay');
    if (!loadingOverlay) return;
    
    const progressFill = loadingOverlay.querySelector('.planner-progress-fill');
    const progressText = loadingOverlay.querySelector('.planner-progress-text');
    
    const percent = total > 0 ? (current / total) * 100 : 0;
    
    if (progressFill) {
        progressFill.style.width = `${percent}%`;
    }
    if (progressText) {
        progressText.textContent = `${current}/${total} etapas`;
    }
}

