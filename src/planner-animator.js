export async function playPlanner(plannerLayers, productName, looping = false, availability = 0, shiftStart = 0, lunchStart = 0, lunchEnd = 0) {
    // SEMPRE parar qualquer execução anterior primeiro
    if (isPlaying) {
        console.warn('[PlannerAnimator] Parando execução anterior antes de começar nova');
        stopPlanner();
    }
    
    // ========== PRÉ-CÁLCULO DE ROTAS (FASE PRE_COMPUTING) ==========
    setPlannerState(PLANNER_STATE.PRE_COMPUTING);
    
    // Verificar se precisa pré-calcular
    const cacheValid = isCacheValid();
    
    if (!cacheValid) {
        
        // Mostrar loading IMEDIATAMENTE para debug
        showLoadingOverlay();
        updateLoadingProgress(0, 1);
        
        // Pequena pausa para garantir que o overlay apareça
        await new Promise(resolve => setTimeout(resolve, 50));
        
        const startCheckTime = performance.now();
        
        try {
            const result = await preComputeRoutes(
                plannerLayers, 
                window.findPathWithAnchors,
                (current, total) => {
                    updateLoadingProgress(current, total);
                }
            );
            
            hideLoadingOverlay();
            
            const elapsed = performance.now() - startCheckTime;
            
            if (result.reusedCount > 0) {
                console.log(`[PlannerAnimator] ♻️ ${result.reusedCount} rotas reutilizadas do cache, ${result.newCount} novas calculadas`);
            }
            
            if (!result.success && result.failCount > 0) {
                console.warn(`[PlannerAnimator] ⚠️ ${result.failCount} rotas falharam no pré-cálculo`);
            }
            
            // Mostrar lembrete para salvar
            showSaveReminder(result);
        } catch (error) {
            hideLoadingOverlay();
            console.error('[PlannerAnimator] ❌ Erro no pré-cálculo:', error);
        }
    } else {
    }
    
    setPlannerState(PLANNER_STATE.PLAYING);
    // ========== FIM DO PRÉ-CÁLCULO ==========

    // Limpar tokens de acabados anteriores ao iniciar nova execução
    clearAllFinishedTokens();

    // Inicializar estoque de acabados a partir do estoque inicial dos recursos
    resources.forEach(resource => {
        if (resource.initialStock && resource.initialStock > 0) {
            const resourceHubs = getHubsForResource(resource.id);
            if (resourceHubs.length > 0) {
                // Distribuir estoque no primeiro hub do recurso
                addFinishedToHub(resourceHubs[0].id, resource.initialStock);
            }
        }
    });

    isLoopingEnabled = looping;
    totalAvailabilityTime = Number(availability) || 0;
    shiftStartSeconds = Number(shiftStart) || 0;
    lunchStartSeconds = Number(lunchStart) || 0;
    lunchEndSeconds = Number(lunchEnd) || 0;
    simulationTime = 0;
    lastFrameTime = 0;
    firstCycleTime = null;
    layersCompletedFirstCycle.clear();
    operatorTimeTracking.clear();
    bottleneckOperatorId = null;
    
    // Resetar métricas ao iniciar nova execução
    updateCycleTimeMetric(null);
    updateValueTimeMetrics(null, null);
    
    if (timerElement) {
        timerElement.style.display = totalAvailabilityTime > 0 ? 'flex' : 'none';
        updateTimerDisplay(0);
    }
    
    // PRIMEIRO: Limpar conexões auto-geradas antigas ANTES de criar novas
    clearAutoGeneratedConnections();
    
    // SEGUNDO: Garantir que não há animações/sprites anteriores
    stopAllConnectionAnimations();
    
    // Limpar qualquer sprite órfão no layer
    if (layerElement) {
        const orphanSprites = layerElement.querySelectorAll('.planner-operator-sprite, .connection-operator');
        orphanSprites.forEach(sprite => sprite.remove());
        
        const orphanBubbles = layerElement.querySelectorAll('.planner-speech-bubble');
        orphanBubbles.forEach(bubble => bubble.remove());
    }
    
    // Organizar em timelines sequenciais (uma por camada)
    plannerData = plannerLayers.map(layer => ({
        layerId: layer.id,
        color: layer.color || null,
        timeline: organizeByOperator(layer.columns, layer.operatorId)
    })).filter(data => data.timeline.length > 0);
    
    if (!plannerData || plannerData.length === 0) {
        console.error('[PlannerAnimator] Nenhuma ação configurada');
        alert('Configure pelo menos uma ação no roteiro');
        setConnectionAnimationsEnabled(true);
        return;
    }
    
    // Coletar todos os operadores de todas as timelines
    const allActions = plannerData.flatMap(d => d.timeline);
    const operatorIds = allActions.map(a => a.operatorId);
    const uniqueIds = new Set(operatorIds);

    setConnectionAnimationsEnabled(false);
    isPlaying = true;
    layerProgress.clear();
    layerLoopCounters.clear();
    plannerData.forEach((_, index) => layerProgress.set(index, 0));
    
    // Inicializar contagem de ciclos
    operatorCycleCounts.clear();
    uniqueIds.forEach(id => operatorCycleCounts.set(id, 0));
    updateOperatorCyclesTable(operatorCycleCounts, operatorTimeTracking);
    
    // Inicializar estados dos operadores (apenas os que aparecem na timeline)
    operatorStates.clear();
    const uniqueOperators = new Set(operatorIds);
    
    // IMPORTANTE: Mapear IDs fictícios para operadores reais para evitar duplicação
    const operatorIdMapping = new Map(); // fictício -> real
    
    // Primeiro pass: identificar todos os operadores reais disponíveis
    const availableOperators = resources.filter(r => r.type === 'operator');
    
    console.log(`%c[MoveLog] ═══ PLAY PLANNER ═══`, 'color: #ff6b00; font-weight: bold; font-size: 14px');
    console.log(`[MoveLog] Resources no andar atual: ${resources.length} (operadores: ${availableOperators.length})`);
    console.log(`[MoveLog] Operadores no roteiro (uniqueOperators):`, Array.from(uniqueOperators));
    availableOperators.forEach(op => {
        console.log(`[MoveLog]   Operador: "${op.name}" (${op.id}) pos=(${op.x}, ${op.y})`);
    });
    
    if (availableOperators.length === 0) {
        console.error('[PlannerAnimator] ✗ Nenhum operador encontrado no layout!');
        alert('Adicione pelo menos um operador ao layout antes de executar o roteiro');
        setConnectionAnimationsEnabled(true);
        return;
    }
    
    // Se há múltiplos IDs fictícios mas apenas 1 operador real, mapear TODOS para o mesmo operador
    // Lógica simplificada: se o ID não existe, pega o primeiro disponível
    
    uniqueOperators.forEach(operatorId => {
        let operator = resources.find(r => r.id === operatorId);
        
        // Se não encontrou por ID exato, mapear para um operador disponível
        if (!operator) {
            console.warn(`[PlannerAnimator] ⚠ ID "${operatorId}" não encontrado, buscando operador disponível...`);
            // Tentar distribuir operadores se possível, ou usar o primeiro
            const opIndex = Array.from(uniqueOperators).indexOf(operatorId);
            operator = availableOperators[opIndex % availableOperators.length];
            
            if (operator) {
                operatorIdMapping.set(operatorId, operator.id);
            }
        } else {
            operatorIdMapping.set(operatorId, operator.id);
        }
    });
    
    // Consolidar timeline: substituir IDs fictícios pelo ID real do operador
    plannerData.forEach(layerData => {
        layerData.timeline.forEach(action => {
            const realId = operatorIdMapping.get(action.operatorId);
            if (realId && realId !== action.operatorId) {
                action.operatorId = realId;
            }
        });
    });
    
    // Reconstruir conjunto de operadores únicos após consolidação
    const consolidatedOperators = new Set(plannerData.flatMap(d => d.timeline).map(a => a.operatorId));
    
    consolidatedOperators.forEach(operatorId => {
        let operator = resources.find(r => r.id === operatorId);
        
        if (!operator) {
            console.error(`[PlannerAnimator] ✗ Operador consolidado ${operatorId} não encontrado - isto não deveria acontecer!`);
            return; // Pular este operador
        }
        
        let initialPos = null;
        let initialHubId = null;
        let resourceVisibilityBackup;
        
        if (operator) {
            // Começar na posição do operador no layout
            initialPos = {
                x: operator.x + (operator.width || 50) / 2,
                y: operator.y + (operator.height || 50) / 2
            };
            
            // Verificar se operador está em um hub no início
            initialHubId = findHubAtPosition(initialPos);
            if (initialHubId) {
            } else {
                // Se não está em nenhum hub, criar um "hub virtual" na posição inicial
                initialHubId = `virtual_hub_${operatorId}_start`;
            }

            resourceVisibilityBackup = Object.prototype.hasOwnProperty.call(operator, 'visible')
                ? operator.visible
                : undefined;

            operator.visible = false;
            operator._plannerHidden = true;
        }
        
        operatorStates.set(operatorId, {
            position: initialPos,
            sprite: null,
            movementStartPos: null,
            movementTargetPos: null,
            movementStartTime: null,
            movementDuration: 0,
            workStartTime: null,
            workDuration: 0,
            phase: 'idle', // 'idle', 'moving', 'working', 'waiting_finished'
            currentStepTargetId: null,
            pathPoints: [],
            pathProgress: 0,
            currentPathSegment: 0,
            lastHubId: initialHubId, // Rastrear último hub onde esteve (incluindo virtual)
            virtualHubPosition: initialHubId?.startsWith('virtual_hub_') ? initialPos : null, // Guardar posição do hub virtual
            facingAngle: 0,
            resourceRef: operator || null,
            resourceVisibilityBackup,
            // Estado para ações de acabados
            isCarryingFinished: false, // Se está carregando um acabado
            carryingToken: null, // Elemento visual do token sendo carregado
            waitingForFinishedAt: null, // Hub onde está aguardando acabado
            pendingWaitForFinished: null, // Hub para esperar após chegar (usado quando precisa se mover primeiro)
            pendingMoveAfterPickup: null // Destino para mover após pegar acabado (usado por 'mover acabado para')
        });
    });

    redraw();

    startAnimation();
}

export function stopPlanner() {
    if (!isPlaying) return;
    
    // Gravar tempo do ciclo: usar o tempo do primeiro ciclo completo se disponível;
    // senão derivar da soma VA+NVA do operador com maior tempo acumulado para garantir
    // consistência entre as três métricas (eliminando artefatos de frame-rate).
    let cycleTimeToReport;
    if (firstCycleTime !== null) {
        cycleTimeToReport = firstCycleTime;
    } else if (bottleneckOperatorId && operatorTimeTracking.has(bottleneckOperatorId)) {
        const bt = operatorTimeTracking.get(bottleneckOperatorId);
        cycleTimeToReport = (bt.valueAddedMs + bt.nonValueAddedMs) / 1000;
    } else {
        // Fallback final: usar o operador com maior tempo total
        let maxTotal = 0;
        for (const [, times] of operatorTimeTracking) {
            const total = times.valueAddedMs + times.nonValueAddedMs;
            if (total > maxTotal) maxTotal = total;
        }
        cycleTimeToReport = maxTotal / 1000;
    }
    updateCycleTimeMetric(cycleTimeToReport, shiftStartSeconds, lunchStartSeconds, lunchEndSeconds);
    
    // Atualizar métricas de tempo agrega/não agrega do operador gargalo
    if (bottleneckOperatorId && operatorTimeTracking.has(bottleneckOperatorId)) {
        const bt = operatorTimeTracking.get(bottleneckOperatorId);
        updateValueTimeMetrics(bt.valueAddedMs / 1000, bt.nonValueAddedMs / 1000);
    } else {
        // Fallback: usar o operador com maior tempo total
        let maxTotal = 0;
        let displayVA = 0, displayNVA = 0;
        for (const [opId, times] of operatorTimeTracking) {
            const total = times.valueAddedMs + times.nonValueAddedMs;
            if (total > maxTotal) {
                maxTotal = total;
                displayVA = times.valueAddedMs;
                displayNVA = times.nonValueAddedMs;
            }
        }
        updateValueTimeMetrics(displayVA / 1000, displayNVA / 1000);
    }
    
    isPlaying = false;
    setPlannerState(PLANNER_STATE.IDLE);
    
    if (animationFrameId) {
        cancelAnimationFrame(animationFrameId);
        animationFrameId = null;
    }
    
    // PRIMEIRO: Parar todas as animações antigas de conexões
    stopAllConnectionAnimations();
    setConnectionAnimationsEnabled(true);
    
    // SEGUNDO: Limpar sprites dos operadores do planner
    operatorStates.forEach((state, operatorId) => {
        if (state.sprite) {
            state.sprite.remove();
        }
        removeSpeechBubble(operatorId);

        if (state.resourceRef) {
            if (state.resourceVisibilityBackup === undefined) {
                delete state.resourceRef.visible;
            } else {
                state.resourceRef.visible = state.resourceVisibilityBackup;
            }
            delete state.resourceRef._plannerHidden;
        }
    });
    
    operatorStates.clear();
    layerProgress.clear();
    layerLoopCounters.clear();
    
    // Limpar tokens sendo carregados (mas manter os de acabados nos hubs)
    if (layerElement) {
        const carryingTokens = layerElement.querySelectorAll('.planner-carrying-token');
        carryingTokens.forEach(t => t.remove());
    }

    // Garantir que conexões auto-geradas fiquem estáticas após o roteiro
    const plannerConnections = getConnections();
    plannerConnections.forEach(connection => {
        if (connection?.isAutoGenerated) {
            connection.disableAutoAnimation = true;
        }
    });
    
    // Limpar highlight
    clearPlannerHighlight();
    
    // NÃO limpar conexões auto-geradas - mantê-las visíveis
    // clearAutoGeneratedConnections();

    // Disparar evento para atualizar UI
    window.dispatchEvent(new CustomEvent('planner:stopped'));

    if (timerElement) {
        // Atualizar o relógio com o tempo exato do ciclo antes de esconder,
        // garantindo que o último valor visível seja idêntico ao card "Tempo do Ciclo".
        updateTimerDisplay(cycleTimeToReport);
        timerElement.style.display = 'none';
    }

    redraw();
}

